const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('forEditor', Object.freeze({
  listMedia: () => ipcRenderer.invoke('media:list'),
  listFolders: () => ipcRenderer.invoke('media:folders'),
  chooseDestination: () => ipcRenderer.invoke('media:choose-destination'),
  listPeople: () => ipcRenderer.invoke('people:list'),
  listTaxonomy: () => ipcRenderer.invoke('taxonomy:list'),
  addTaxonomy: (data) => ipcRenderer.invoke('taxonomy:add', data),
  removeTaxonomy: (data) => ipcRenderer.invoke('taxonomy:remove', data),
  addPerson: (name) => ipcRenderer.invoke('people:add', name),
  importMedia: () => ipcRenderer.invoke('media:import'),
  importFolder: () => ipcRenderer.invoke('media:import-folder'),
  updateMedia: (data) => ipcRenderer.invoke('media:update', data),
  updateMediaBatch: (data) => ipcRenderer.invoke('media:update-batch', data),
  removeMedia: (id) => ipcRenderer.invoke('media:remove', id),
  copyMedia: (id) => ipcRenderer.invoke('media:copy', id),
  openMedia: (id) => ipcRenderer.invoke('media:open', id),
  youtubeFormats: (url) => ipcRenderer.invoke('web:youtube-formats', url),
  youtubeDownload: (url, formatId, folderId) => ipcRenderer.invoke('web:youtube-download', { url, formatId, folderId }),
  imageSearch: (query) => ipcRenderer.invoke('web:image-search', query),
  imageMore: (query) => ipcRenderer.invoke('web:image-more', query),
  pinterestStatus: () => ipcRenderer.invoke('accounts:pinterest-status'),
  pinterestLogin: () => ipcRenderer.invoke('accounts:pinterest-login'),
  pinterestOpen: (query) => ipcRenderer.invoke('accounts:pinterest-open', query),
  pinterestDisconnect: () => ipcRenderer.invoke('accounts:pinterest-disconnect'),
  imageSave: (data) => ipcRenderer.invoke('web:image-save', data),
  imageCopy: (url) => ipcRenderer.invoke('web:image-copy', url),
  onWebProgress: (callback) => { const listener = (_event, value) => callback(value); ipcRenderer.on('web:progress', listener); return () => ipcRenderer.removeListener('web:progress', listener); },
}));
